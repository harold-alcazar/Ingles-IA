const fs = require('fs');
const path = require('path');

const supabaseUrl = 
  process.env.VITE_SUPABASE_URL || 
  process.env.SUPABASE_URL || 
  'https://placeholder-project.supabase.co';

const supabaseAnonKey = 
  process.env.VITE_SUPABASE_ANON_KEY || 
  process.env.SUPABASE_ANON_KEY || 
  'placeholder-anon-key';

const envConfigFile = `// This file is auto-generated by scripts/set-env.js during build
export const environment = {
  production: true,
  supabaseUrl: '${supabaseUrl.trim()}',
  supabaseAnonKey: '${supabaseAnonKey.trim()}'
};
`;

const targetDir = path.join(__dirname, '../src/environments');
const targetPath = path.join(targetDir, 'environment.ts');

if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

fs.writeFileSync(targetPath, envConfigFile, 'utf8');
console.log(`[set-env] Successfully generated ${targetPath} with Supabase target.`);
